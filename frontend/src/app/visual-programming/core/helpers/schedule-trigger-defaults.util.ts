import { ScheduleTriggerNodeData } from '../models/schedule-trigger.model';

const MONTH_LABELS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const WEEKDAY_ORDER = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
const WEEKDAY_LABELS: Record<string, string> = {
    sun: 'Sun',
    mon: 'Mon',
    tue: 'Tue',
    wed: 'Wed',
    thu: 'Thu',
    fri: 'Fri',
    sat: 'Sat',
};
const SINGULAR_UNITS: Record<string, string> = {
    seconds: 'second',
    minutes: 'minute',
    hours: 'hour',
    days: 'day',
    weeks: 'week',
    months: 'month',
};
const MINUTES_PER_SLOT = 30;
const MAX_LISTED_WEEKDAYS = 3;

/**
 * The start a new schedule proposes: the browser's wall clock rounded up to the next :00 or :30,
 * always in the future (exactly 10:30 becomes 11:00). Returned as the naive ISO string the schedule
 * stores ("YYYY-MM-DDTHH:MM:00", no offset): the timezone travels separately.
 */
export function defaultScheduleStartDateTime(now: Date = new Date()): string {
    const start = new Date(now.getTime());
    start.setSeconds(0, 0);
    const minutesPastSlot = start.getMinutes() % MINUTES_PER_SLOT;
    start.setMinutes(start.getMinutes() + MINUTES_PER_SLOT - minutesPastSlot);

    const pad = (value: number) => String(value).padStart(2, '0');
    return (
        `${start.getFullYear()}-${pad(start.getMonth() + 1)}-${pad(start.getDate())}` +
        `T${pad(start.getHours())}:${pad(start.getMinutes())}:00`
    );
}

/** The name a schedule node gets while the user has not named it themselves, e.g. "Once on 23 Oct 2026 at 13-00". */
export function generateScheduleName(data: ScheduleTriggerNodeData): string {
    if (data.runMode === 'once') {
        if (data.startDateTime) {
            // Use hyphen separator ("HH-MM") to avoid colon ambiguity in file-system
            // derived artifacts and visual display. Legacy names with "HH:MM" are still
            // recognised as auto-generated by the panel and rewritten on the next edit.
            const rawTime = data.startDateTime.split('T')[1]?.slice(0, 5) ?? '';
            const timePart = rawTime.replace(':', '-');
            return `Once on ${formatDateForName(data.startDateTime)} at ${timePart}`;
        }
        return 'One-time schedule';
    }

    const every = data.intervalEvery ?? 1;
    const unit = data.intervalUnit ?? 'hours';
    let name = every === 1 ? `Every ${SINGULAR_UNITS[unit] ?? unit}` : `Every ${every} ${unit}`;

    if (unit === 'weeks' && data.weekdays && data.weekdays.length > 0) {
        if (data.weekdays.length <= MAX_LISTED_WEEKDAYS) {
            const sorted = [...data.weekdays].sort((a, b) => WEEKDAY_ORDER.indexOf(a) - WEEKDAY_ORDER.indexOf(b));
            name += ' on ' + sorted.map((day) => WEEKDAY_LABELS[day] ?? day).join(', ');
        } else {
            name += ' on selected days';
        }
    }

    if (data.endType === 'on_date' && data.endDateTime) {
        name += ` until ${formatDateForName(data.endDateTime)}`;
    } else if (data.endType === 'after_n_runs' && data.maxRuns != null) {
        name += ` for ${data.maxRuns} ${data.maxRuns === 1 ? 'run' : 'runs'}`;
    }

    return name;
}

/** "2026-10-23T13:00:00" → "23 Oct 2026", read from the string itself so the browser timezone cannot shift it. */
function formatDateForName(iso: string): string {
    const [year, month, day] = iso.split('T')[0].split('-').map(Number);
    return `${String(day).padStart(2, '0')} ${MONTH_LABELS[month - 1]} ${year}`;
}
