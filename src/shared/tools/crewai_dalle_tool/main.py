# Dall-E Image Generator Tool
#
# `api_key` is NOT a function parameter: args_schema.json declares it with
# "input_type": "user_input", so it is set in the tool configuration and the
# sandbox injects it as a module-level global -- the agent never sees it.
import json
from pydantic import BaseModel, Field
from openai import OpenAI
from epicstaff_common import require_setting, safe_error_message


class ImagePromptSchema(BaseModel):
    """Input schema for Dall-E image generation."""
    image_description: str = Field(..., description="Description of the image to be generated by Dall-E.")


def main(image_description: str, **kwargs) -> str:
    """
    Generate an image using OpenAI Dall-E.

    Args:
        image_description (str): The prompt describing the image.

    Returns:
        str: JSON string containing image URL and prompt.
    """
    if not image_description:
        return json.dumps({"error": "Image description is required."})

    try:
        client = OpenAI(api_key=require_setting(globals(), "api_key"))

        response = client.images.generate(
            model="dall-e-3",
            prompt=image_description,
            size="1024x1024",
            quality="standard",
            n=1,
        )
    except Exception as error:
        return json.dumps({"error": safe_error_message(error)})

    image_data = {
        "image_url": response.data[0].url,
        "image_description": getattr(response.data[0], "revised_prompt", image_description)
    }

    return json.dumps(image_data)
