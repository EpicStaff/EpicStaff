"""A clock the test moves by hand, for code that takes a ``clock`` callable."""

__all__ = ["FakeClock"]


class FakeClock:
    def __init__(self, now: float = 1000.0) -> None:
        self.now = now

    def __call__(self) -> float:
        return self.now

    def advance(self, seconds: float) -> None:
        self.now += seconds
