def render_description(text: str) -> str:
    lines = textwrap.wrap(
        text,
        width=100,
        initial_indent="# ",
        subsequent_indent="# ",
        break_long_words=False,
        break_on_hyphens=False,
    )
    return "\n" + "\n".join(lines) + "\n"


def resolve_default(declaration: dict, target: Literal["prod", "dev"]):
    default = declaration.get("default")
